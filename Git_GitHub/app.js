// Basic commands
// clone - git clone <repo_url> - Clone a repository
// status - git status - Check the status of your repository
// add - git add <file_name> - Add files to staging area
// commit - git commit -m "commit message" - Commit changes with a message
// push - git push origin <branch_name> - Push changes to remote repository
// pull - git pull origin <branch_name> - Pull changes from remote repository